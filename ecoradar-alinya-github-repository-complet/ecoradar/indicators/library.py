"""Central EcoRadar indicator definitions.

This module defines the indicator catalogue only. It does not calculate scores,
recommend management actions, or interpret project data.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable


@dataclass(frozen=True)
class IndicatorDefinition:
    """Static definition of an EcoRadar indicator."""

    code: str
    name: str
    thematic_block: str
    objective: str
    required_data: tuple[str, ...]
    data_sources: tuple[str, ...]
    calculation_method: str
    valuation_scale: str
    confidence_level: str
    limitations: tuple[str, ...]
    associated_recommendations: tuple[str, ...]
    calculation_status: str = "not_implemented"


def _indicator(
    code: str,
    name: str,
    block: str,
    objective: str,
    required_data: Iterable[str],
    sources: Iterable[str],
    method: str,
    scale: str,
    recommendations: Iterable[str],
    limitations: Iterable[str] = (),
) -> IndicatorDefinition:
    return IndicatorDefinition(
        code=code,
        name=name,
        thematic_block=block,
        objective=objective,
        required_data=tuple(required_data),
        data_sources=tuple(sources),
        calculation_method=method,
        valuation_scale=scale,
        confidence_level="pendent_dades; alta si totes les fonts requerides son verificades i actuals",
        limitations=tuple(limitations)
        or (
            "Definicio de biblioteca: el calcul real encara no esta implementat.",
            "La puntuacio 0-100 s'ha de validar amb dades locals i criteri tecnic.",
        ),
        associated_recommendations=tuple(recommendations),
    )


