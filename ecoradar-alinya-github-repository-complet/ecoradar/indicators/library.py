_INDICATORS_BY_CODE = {indicator.code: indicator for indicator in INDICATORS}


def list_indicators() -> tuple[IndicatorDefinition, ...]:
    """Return all indicator definitions in library order."""

    return INDICATORS


def get_indicator(code: str) -> IndicatorDefinition:
    """Return one indicator by code."""

    try:
        return _INDICATORS_BY_CODE[code]
    except KeyError as exc:
        known = ", ".join(sorted(_INDICATORS_BY_CODE))
        raise KeyError(f"Unknown indicator '{code}'. Known indicators: {known}") from exc


def indicators_by_block(block: str) -> tuple[IndicatorDefinition, ...]:
    """Return all indicators belonging to a thematic block."""

    return tuple(indicator for indicator in INDICATORS if indicator.thematic_block == block)
